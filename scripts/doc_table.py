#!/usr/bin/env python3
"""doc_table.py [--check] -- writes crates/cas-lang/names/en_docs.txt from giac's help (CAS-669).

Reads /usr/share/giac/aide_cas (xcas 2.0.0.21+dfsg2-3+b1, refused unless its sha256 is the pin)
through aide.py's positional reader, crates/cas-lang/names/en.txt (names to targets) and the
departure items of crates/cas-giac/README.md `## Tests`. One record per [builtins] or [constants]
target that has an aide_cas entry (CAS-DOC-60 §6). Output sorted by target, byte-identical between
runs. --check compares with the committed file instead of writing it (exit 1 on a difference).
Notes (entries that lost a target, repeated lines) go to stderr. Runs locally only: CI has no xcas.
"""
import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aide  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EN = os.path.join(ROOT, "crates/cas-lang/names/en.txt")
OUT = os.path.join(ROOT, "crates/cas-lang/names/en_docs.txt")
README = os.path.join(ROOT, "crates/cas-giac/README.md")
README_REL = "crates/cas-giac/README.md"
PACKAGE = "xcas 2.0.0.21+dfsg2-3+b1"
SHA256 = "c32a40d185b79735b02ec49f3c64b9a936108708abf69ab26e9362d06cebf2a8"

HEADER = """\
# English documentation of cas-lang's builtins, by target (CAS-DOC-60 §6, CAS-669).
# Generated by scripts/doc_table.py; never hand-edited (H1). Hand edits go in
# en_docs_overlay.txt. Rerun the script after a change to its inputs; --check
# compares.
#
# Source: /usr/share/giac/aide_cas, giac's help, from the Debian package
# {package}, sha1 {sha1}
# (sha256 {sha256}).
# aide_cas is Copyright 2000-2017 Bernard Parisse, Renée de Graeve, Jose
# Manrique Lopez de la Fuente, X. Vidaux and Alkis Akritas, licensed GPL-3+
# (/usr/share/doc/libgiac0t64/copyright, Files: doc/aide_cas).
# This file is extracted from aide_cas and changed (GPL-3 §5a), 2026-11-28:
# only the names, the `0` signature, the English `2` line, the related names
# and the examples are kept; names are mapped to cas-lang targets, related
# names not ours are dropped, and each record gains the departure items of
# crates/cas-giac/README.md `## Tests` that call it. Examples our parser
# rejects are hidden at load.
#
# Format: `[Target]` (an en.txt [builtins] key, or `imaginary`), then
# `giac:` the entry's names, `sig:` the `0` line, `doc:` the `2` line,
# `see:` related targets, `ex:` one example each, `dep: <README line> <text>`
# one departure each. Values are single lines.
"""


def sections(path):
    """en.txt's [builtins] and [constants]: (targets {key: [names]}, name -> key)."""
    targets, owner, section = {}, {}, None
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("["):
                section = line.strip("[]")
                continue
            if section in ("builtins", "constants") and ":" in line:
                key, names = line.split(":", 1)
                key, names = key.strip(), names.split()
                targets[key] = names
                for n in names:
                    owner[n] = key
    return targets, owner


def departures(path):
    """README `## Tests` items (list items and paragraphs) that mention a departure:
    [(first line number, text joined on one line, called names)]."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("## Tests"))
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    items, cur = [], None
    for i in range(start + 1, end):
        l = lines[i]
        if not l.strip():
            cur = None
        elif re.match(r"^\s*- ", l) or cur is None:
            cur = [i + 1, [l.strip()]]
            items.append(cur)
        else:
            cur[1].append(l.strip())
    out = []
    for line, parts in items:
        text = " ".join(parts)
        if not re.search(r"depart", text, re.I):
            continue
        calls = []
        for span in re.findall(r"`([^`]*)`", text):
            m = re.match(r"([A-Za-z_][\w]*)\(", span)
            if m and m.group(1) not in calls:
                calls.append(m.group(1))
        out.append((line, text, calls))
    return out


def build():
    with open(aide.AIDE, "rb") as f:
        data = f.read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit(f"doc_table.py: {aide.AIDE} is not {PACKAGE}'s (sha256 differs); re-pin deliberately")
    sha1 = hashlib.sha1(data).hexdigest()
    targets, owner = sections(EN)
    entries = aide.entries()
    chosen = {}
    for e in entries:
        for t in dict.fromkeys(owner[n] for n in e["names"] if n in owner):
            chosen.setdefault(t, []).append(e)
    for e in entries:
        for line, text in e["dups"]:
            print(f"note: aide_cas:{line} repeated line skipped: {text}", file=sys.stderr)
    deps = departures(README)
    out = [HEADER.format(package=PACKAGE, sha1=sha1, sha256=SHA256)]
    for t in sorted(chosen):
        cands, spelling = chosen[t], targets[t][0]
        e = next((c for c in cands if c["names"][0] == spelling), None) \
            or next((c for c in cands if spelling in c["names"]), cands[0])
        for c in cands:
            if c is not e:
                print(f"note: [{t}] aide_cas:{c['line']} `{' '.join(c['names'])}` loses to "
                      f"aide_cas:{e['line']}", file=sys.stderr)
        rec = [f"[{t}]", "giac: " + " ".join(e["names"])]
        if e["sig"]:
            rec.append("sig: " + e["sig"])
        if e["en"]:
            rec.append("doc: " + e["en"])
        see = [s for s in dict.fromkeys(owner[n] for n in e["related"] if n in owner) if s != t]
        if see:
            rec.append("see: " + " ".join(see))
        rec += ["ex: " + x.strip() for x in e["ex"] if x.strip()]
        names = set(targets[t])
        rec += [f"dep: {line} {text}" for line, text, calls in deps if names & set(calls)]
        out.append("\n".join(rec) + "\n")
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit(f"doc_table.py: {OUT} differs from a fresh run")
        print("en_docs.txt is current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
