//! Embeds the tuning configuration: the thresholds that pick algorithms by
//! operand size.
//!
//! The file is `tuning/default.toml`, or the one named by the environment
//! variable `CAS_NUM_TUNING` (relative paths resolve against this crate's
//! directory; in `.cargo/config.toml`, `[env] CAS_NUM_TUNING = { value =
//! "...", relative = true }` makes them relative to that file). Each line is
//! `key = value`, with `#` comments; every key below must appear exactly once.
//! The values become `const`s in `OUT_DIR/tuning.rs`, so they fold into the
//! code exactly as literals would.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// `(key, minimum)`. Every algorithm is correct for any value at or above
/// its minimum; below it some algorithm would be called outside its domain.
const KEYS: [(&str, u64); 26] = [
    // A 1x1 product would be "chunked" into 1x1 products forever.
    ("mul_karatsuba_threshold", 2),
    // Toom-3 checks its own balance condition, so any size works.
    ("mul_toom3_threshold", 1),
    // Toom-4 checks its own balance condition too.
    ("mul_toom4_threshold", 1),
    ("mul_ntt_threshold", 1),
    // Karatsuba squaring needs n > ceil(n / 2).
    ("sqr_karatsuba_threshold", 2),
    // Toom-3 squaring needs n > 2 ceil(n / 3), false only for n <= 2 and n = 4.
    ("sqr_toom3_threshold", 5),
    // Toom-4 squaring checks n > 3 ceil(n / 4) and leaves the rest to Toom-3.
    ("sqr_toom4_threshold", 1),
    ("sqr_ntt_threshold", 1),
    // Any exponent only moves products between correct algorithms.
    ("ntt_efficiency_exponent", 0),
    ("ntt_block", 1),
    // A divisor: wrap when 2e - 1 <= n / ntt_wrap_fraction.
    ("ntt_wrap_fraction", 1),
    ("mul_wrap_ntt_threshold", 1),
    // Divide and conquer splits off a non-empty half for the cross terms.
    ("mullo_dc_threshold", 2),
    ("mullo_mul_threshold", 1),
    // Divide and conquer splits the divisor in two non-empty halves.
    ("dc_div_threshold", 2),
    ("mu_div_threshold", 2),
    // A Newton step on n limbs recurses on n / 2 + 1, below n only from 3.
    ("inv_newton_threshold", 3),
    ("bdiv_mu_threshold", 1),
    // A 2-adic Newton step on n limbs recurses on ceil(n / 2), below n from 2.
    ("binv_newton_threshold", 2),
    ("divexact_div_threshold", 1),
    ("redc_n_threshold", 1),
    ("gcd_dc_threshold", 1),
    // Below 3 limbs the first recursive half-GCD could leave values under B^s.
    ("hgcd_threshold", 3),
    ("matrix22_strassen_threshold", 1),
    ("to_string_dc_threshold", 1),
    // Parsing by divide and conquer needs more digits than one limb holds.
    ("from_string_dc_threshold", 65),
];

fn fail(msg: &str) -> ! {
    panic!("cas-num tuning configuration: {msg}");
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("set by cargo"));
    println!("cargo:rerun-if-env-changed=CAS_NUM_TUNING");
    let path = env::var_os("CAS_NUM_TUNING").map_or_else(
        || manifest.join("tuning/default.toml"),
        |p| manifest.join(p),
    );
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|e| fail(&format!("cannot read {}: {e}", path.display())));

    let mut values = BTreeMap::new();
    for (number, line) in text.lines().enumerate() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let at = |msg: &str| -> ! { fail(&format!("{}:{}: {msg}", path.display(), number + 1)) };
        let Some((key, value)) = line.split_once('=') else {
            at("expected `key = value`");
        };
        let key = key.trim();
        let Some(&(_, min)) = KEYS.iter().find(|(k, _)| *k == key) else {
            at(&format!("unknown key `{key}`"));
        };
        let value: u64 = value
            .trim()
            .replace('_', "")
            .parse()
            .unwrap_or_else(|_| at(&format!("`{key}` is not a non-negative integer")));
        if value < min {
            at(&format!("`{key}` = {value} is below its minimum {min}"));
        }
        if usize::try_from(value).is_err() {
            at(&format!("`{key}` = {value} does not fit a usize"));
        }
        if values.insert(key, value).is_some() {
            at(&format!("`{key}` appears twice"));
        }
    }

    let mut out = format!("// Generated by build.rs from {}.\n", path.display());
    for (key, _) in KEYS {
        let value = values
            .get(key)
            .unwrap_or_else(|| fail(&format!("{}: missing `{key}`", path.display())));
        writeln!(
            out,
            "pub(crate) const {}: usize = {value};",
            key.to_ascii_uppercase()
        )
        .expect("writing to a String");
    }
    let dest = PathBuf::from(env::var_os("OUT_DIR").expect("set by cargo")).join("tuning.rs");
    fs::write(dest, out).expect("writing OUT_DIR/tuning.rs");
}
